#!/usr/bin/env bash
#
# Готовит инфраструктуру ассистента по файлам проекта (один раз перед демо):
#   1. собирает cliJvmApp + projectfs-mcp (installDist);
#   2. проверяет целевой репозиторий и заводит в нём отдельную ветку для правок;
#   3. собирает суженный RAG-корпус и индексирует его;
#   4. заливает два профиля - fs-explorer/fs-reporter, нарезанные по фазам.
# Идемпотентно: профили и индекс пересобираются заново каждый прогон.
#
# ВАЖНО: профили живут в ~/.project01-cli/memory/profiles/ и правкой ЭТОГО файла не
# обновляются - после любого изменения промптов setup.sh надо перезапустить, иначе
# прогон пойдёт со старым профилем, а отладка будет врать.
#
# Задачи (стадия clarification) кладут в память НЕ здесь, а обёртки run-*.sh - они
# сбрасывают кейс перед каждым запуском чата.
#
# Использование (из корня репозитория):
#   bash demo/project-fs/setup.sh
#   CTT_REPO=/путь/к/репо bash demo/project-fs/setup.sh    # другой целевой репозиторий
#   SKIP_RAG=1 bash demo/project-fs/setup.sh               # без индексации (не жечь токены)
#   PROVIDER=ollama bash demo/project-fs/setup.sh          # индекс локальным эмбеддером, СВОИМ именем
#
# Индекс принадлежит провайдеру: под ollama он и строится локально, и лежит под именем с суффиксом.
# Меняешь PROVIDER - перезапусти setup (без SKIP_RAG), иначе индекса этого бэкенда просто нет.
#
set -euo pipefail

# shellcheck source=demo/project-fs/common.sh
source "$(cd "$(dirname "$0")" && pwd)/common.sh"

require_ctt_repo

echo "[setup] gradle installDist (cliJvmApp + projectfs-mcp)..."
( cd "$REPO_ROOT" && ./gradlew \
    :agenticHubClient:apps:cliJvmApp:installDist \
    :playground:projectfs-mcp:installDist --console=plain )

echo "[setup] целевой репозиторий: $CTT_REPO"
require_clean_tree
switch_to_work_branch
echo "[setup] ветка: $(git -C "$CTT_REPO" branch --show-current)"

# Корпус для RAG: только то, что описывает ТЕКУЩЕЕ состояние проекта.
#
# PLANS/ - архив выполненных планов, .github/ - конфигурация CI. В прогонах прототипа
# именно они стабильно занимали топ выдачи со скором 0.7+ и уводили внимание с живых
# документов: архив описывает прошлые этапы и по формулировкам похож на вопрос об
# устройстве проекта, но отвечает не о нём. Для сценария adr исключение PLANS - ещё и
# условие задачи: готовый план интеграции Room там лежит, и с ним реконструировать
# решение по коду было бы нечего.
#
# Копируем с сохранением относительных путей: `source` в выдаче RAG остаётся тем же
# путём, что и в целевом репозитории, поэтому ссылки из ответа модели ведут куда надо.
build_rag_corpus() {
  rm -rf "$RAG_STAGE"
  mkdir -p "$RAG_STAGE"
  ( cd "$CTT_REPO" && find . \
      \( -name build -o -name .git -o -name .gradle -o -name .idea -o -name PLANS -o -name .github \) -prune -o \
      -type f \( -name '*.md' -o -name '*.kt' -o -name '*.kts' \) -print ) |
    while IFS= read -r rel; do
      rel="${rel#./}"
      mkdir -p "$RAG_STAGE/$(dirname "$rel")"
      cp "$CTT_REPO/$rel" "$RAG_STAGE/$rel"
    done
  find "$RAG_STAGE" -type f | wc -l | tr -d ' '
}

if [ "${SKIP_RAG:-0}" = "1" ]; then
  echo "[setup] SKIP_RAG=1 - индексацию пропускаю"
else
  echo "[setup] собираю корпус RAG..."
  corpus_files="$(build_rag_corpus)"
  echo "[setup] в корпусе $corpus_files файл(ов), индексирую как '$RAG_NAME' (embedder=$RAG_EMBEDDER)..."
  "$CLI" -rag add "$RAG_NAME" src "$RAG_STAGE" embedder "$RAG_EMBEDDER"
fi

# ----------------------------------------------------------------------------------
# Профили.
#
# Их два, и нарезаны они по ФАЗАМ разговора - это и есть способ настроить
# судью, не трогая код. Судья аудирует ответ против `constraints` того профиля, с
# которым говорил ответивший агент, а агент выбирается по стадии; значит смена
# стадийного агента сама меняет мерило. Один профиль на все стадии означал бы одно
# мерило на весь разговор: запрет «не утверждай, что отчёт записан» применялся бы и к
# первой реплике, где никакого отчёта ещё нет и в помине.
#
# Фазы различаются не персоной, а типом опасного утверждения:
#   разведка (clarification..planning) - выдуманные пути, имена и номера строк;
#   производство (execution..done)     - приписанная себе работа, которой не было.
#
# Отсюда форма формулировок. `constraints` - ЗАПРЕТЫ: судья видит ответ, реплику
# пользователя, выполненные за сессию вызовы, стадию и секции format/style, но истории
# диалога у него нет, поэтому требование «делай X» на фазе, где X неуместен, он всё
# равно прочитает как нарушение; запрет «не утверждай X» безопасен всегда.
#
# Проверяемость решается тем, откуда судья узнаёт факт: путь и номер строки он видит в
# аргументах и ответах вызовов, а содержимое RAG-выдачи не видит нигде. Поэтому «не
# называй путь, которого нет в результатах выполненных вызовов» - рабочий критерий, а
# «не противоречь документации» - нет. И улику надо называть ДОСЛОВНО: формулировка
# «не подтверждённые поиском» однажды была прочитана как «не подтверждённые
# ПОЛЬЗОВАТЕЛЕМ», и честный ход отклонили.
#
# Что написано в `context`, судье не достаётся вовсе - там указания агенту, а не
# критерий приёмки. Каждое ограничение сверено с `context` СВОЕГО профиля: трижды подряд
# ограничение карало ровно то, что предписывала инструкция стадии, а заметить этот
# конфликт судья не может по построению.
# ----------------------------------------------------------------------------------

echo "[setup] заливаю профили..."

# --- fs-explorer: разведка для сценариев usage-report / adr --------------------------
"$CLI" -profile clear fs-explorer || true
"$CLI" -profile fs-explorer style "Кратко, по-деловому, по-русски."
"$CLI" -profile fs-explorer style "Не пересказывай то, что уже сказал в предыдущих репликах - продолжай с того места, где остановился."

"$CLI" -profile fs-explorer format "Заканчивай ответ блоком '## Найдено': строки вида 'путь:строка - факт'. Строка обязана нести номер строки и содержательный факт: 'shared/Constants.kt:3 - SERVER_PORT=8080 задан константой' годится, 'AGENTS.md: - server' нет. Пересказ списка файлов из выдачи поиска фактом не является. Если по делу писать нечего - одна строка 'пока нечего'."
"$CLI" -profile fs-explorer format "После блока допустима строка-сигнал '[[stage:<имя>]]' - её требует порядок работы, прозой она не является."

"$CLI" -profile fs-explorer constraints "Не называй путь к файлу, имя класса или номер строки, которых нет в результатах выполненных вызовов инструментов."
"$CLI" -profile fs-explorer constraints "Не утверждай, что термин, класс или файл в проекте отсутствует, если среди выполненных вызовов нет поиска по этому термину."
"$CLI" -profile fs-explorer constraints "Не утверждай, что файл уже создан или изменён."

"$CLI" -profile fs-explorer context "Ты исследуешь проект приложения - состоит из исходных кодов. Дерево читаешь инструментами projectfs - они работают по живому дереву."
"$CLI" -profile fs-explorer context "Блок '## Найдено' - ТВОЯ ЕДИНСТВЕННАЯ ПАМЯТЬ между ходами: содержимое файлов и результаты вызовов в следующий ход не переносятся, переносится только текст ответа. Факт, не попавший в блок, для тебя потерян - придётся искать заново."
"$CLI" -profile fs-explorer context "За один ход делай не больше 4 вызовов инструментов. Не хватило материала - заверши ход сводкой найденного и продолжи в следующем ходе, ОСТАВАЯСЬ в той же стадии."
"$CLI" -profile fs-explorer context "МЕТОД. Ищи ОДНИМ термином - одно слово или одно имя. Поиск литеральный: запрос из нескольких слов ищется как точная подстрока целиком и почти всегда даёт ноль. При пустом результате инструмент подскажет, какие слова встречаются по отдельности - бери термин оттуда и повторяй."
"$CLI" -profile fs-explorer context "МЕТОД. Широкий вопрос начинай с filesOnly=true - это карта территории за долю вывода. Дальше точечные поиски по конкретным терминам."
"$CLI" -profile fs-explorer context "Номер строки бери ИЗ ОТВЕТА инструмента дословно: поиск отдаёт строки вида 'путь:НОМЕР: текст'. Номер по памяти или по догадке - выдумка, даже если сам факт верен."
"$CLI" -profile fs-explorer context "НЕ описывай будущие действия прозой ('Я ищу X', 'проверю все .kt', 'сейчас найду') - это пустой ход. Либо в ЭТОМ ходе есть вызов инструмента, либо ты переходишь на следующую стадию строкой [[stage:...]]."
"$CLI" -profile fs-explorer context "Инструмент вернул 'не найден' или поиск по имени дал ноль - значит в дереве этого нет: значение могло генерироваться системой сборки проекта. Это САМ ПО СЕБЕ факт для отчёта ('источник вне дерева, генерируется'), а не повод перебирать пути. Одно и то же имя разными способами не ищи."
"$CLI" -profile fs-explorer context "Размер каждого файла виден в листинге. Файл до 200 строк читай ЦЕЛИКОМ одним вызовом, без limit - дробить его на куски по 20 строк значит впустую жечь раунды."
"$CLI" -profile fs-explorer context "RAG-подсказки - только наводка: индекс это снимок и после правок устаревает. Любое утверждение проверяй файловым инструментом, а не чанком из выдачи."
"$CLI" -profile fs-explorer context "Стадия clarification: одним list_project_files определи, что вообще в игре, и назови 3-5 конкретных терминов, которые будешь проверять поиском."
"$CLI" -profile fs-explorer context "Стадия planning - это НЕ составление списка будущих проверок, а сами проверки. В сводку идут ФАКТЫ с номерами строк из ответа инструмента, а не намерения."
"$CLI" -profile fs-explorer context "Стадия planning - это не цель: как только общая карта исследования ясна и подтверждена пользователем (или предложено продолжать) - переходи в execution строкой [[stage:execution]]. Обычно хватает 1-2 ходов поиска. Гоняться за одним символом больше двух ходов - ошибка: недостающее пометишь 'не проверено' в отчёте. Отчёт пишется в execution, не здесь."
"$CLI" -profile fs-explorer context "Когда стадия завершена - заканчивай ответ строкой [[stage:<next>]], выбирая одну из allowed-next стадий. Стадии идут строго по порядку: clarification, planning, execution, validation, done. Перепрыгнуть нельзя. Запрошенный через голову переход отклоняется, и ты увидишь строку '[task] model proposed ... not allowed' - увидел её, значит проси СЛЕДУЮЩУЮ по порядку стадию, а не ту же снова."

# --- fs-reporter: запись отчёта для сценариев usage-report / adr ---------------------
#
# Ограничение про запись названо каталогом docs/, а не «файлом, названным в задаче»:
# текста задачи судья не видит вовсе, и такую формулировку ему пришлось бы угадывать.
# Каталог он видит прямо в аргументах вызова - проверка одноходовая.
"$CLI" -profile clear fs-reporter || true
"$CLI" -profile fs-reporter style "Кратко, по-деловому, по-русски."
"$CLI" -profile fs-reporter style "Не пересказывай заново то, что уже собрал на прошлой стадии - продолжай с того места, где остановился."

"$CLI" -profile fs-reporter format "Заканчивай ответ блоком '## Сделано'. Первая строка - путь записанного файла (docs/<report_name>.md), его подтверждает ответ write_project_file с дифом. Ниже - ссылки 'путь:строка' на ИСХОДНЫЙ код, вошедший в отчёт: те же, что собрал на разведке."
"$CLI" -profile fs-reporter format "Ссылки в блоке ведут на исходный код, а НЕ на строки самого отчёта: номер строки внутри только что записанного файла ты чтением не подтверждал, называть его нельзя. Сам отчёт указывай путём без номера строки."
"$CLI" -profile fs-reporter format "После блока допустима строка-сигнал '[[stage:<имя>]]' - её требует порядок работы, прозой она не является."

"$CLI" -profile fs-reporter constraints "Не утверждай, что отчёт записан, если среди выполненных вызовов нет write_project_file с успешным ответом."
"$CLI" -profile fs-reporter constraints "Не записывай ничего за пределами каталога docs/ - единственная запись этой работы лежит в нём."
"$CLI" -profile fs-reporter constraints "Не называй путь к файлу или номер строки, которых нет в результатах выполненных вызовов инструментов."

"$CLI" -profile fs-reporter context "Ты записываешь отчёт по проекту приложения - состоит из исходных кодов. Путь отчёта назван в задаче. Файлы пишешь инструментами projectfs - они работают по живому дереву."
"$CLI" -profile fs-reporter context "Стадия execution: НЕ ищи и не читай больше - собранного достаточно. ПЕРВЫМ вызовом хода обязан быть write_project_file; всё, что не вошло, помечай пробелом ВНУТРИ отчёта. Бюджет инструментов тратится на ход, и если потратить его на добор материала, записать отчёт будет уже нечем."
"$CLI" -profile fs-reporter context "Каждый пункт отчёта - со ссылкой 'путь:строка' на то место, которое ты действительно открывал. Обобщения без ссылки не пиши."
"$CLI" -profile fs-reporter context "Номер строки переноси из результата вызова ДОСЛОВНО. Был в выдаче поиска README.md:126 - пиши 126, а не другое число: изменённый номер судья видит как выдумку и снимает ход."
"$CLI" -profile fs-reporter context "Пункт, по которому в этой сессии НЕ было вызова инструмента с подходящим ответом, обязан иметь статус 'не проверено' и пустую ссылку. Это НОРМАЛЬНЫЙ результат отчёта, а не провал. Написать 'подтверждён' или 'нарушен' без вызова, который это показал, - грубейшая ошибка: она хуже пустого отчёта, потому что выглядит убедительно."
"$CLI" -profile fs-reporter context "Отчёт - не длиннее 60 строк: его содержимое целиком уходит и в контекст, и в транскрипт."
"$CLI" -profile fs-reporter context "Ответ инструмента с дифом - единственное доказательство того, что файл на диске. Без него отчёта нет, как бы уверенно ты о нём ни писал."
"$CLI" -profile fs-reporter context "Стадия validation: перечитай отчёт read_project_file и убедись, что он на диске и полон."
"$CLI" -profile fs-reporter context "Когда стадия завершена - заканчивай ответ строкой [[stage:<next>]], выбирая одну из allowed-next стадий. Стадии идут строго по порядку: clarification, planning, execution, validation, done. Перепрыгнуть нельзя. Запрошенный через голову переход отклоняется, и ты увидишь строку '[task] model proposed ... not allowed' - увидел её, значит проси СЛЕДУЮЩУЮ по порядку стадию, а не ту же снова."

# Глобальных правил у этого демо нет - только очистка, чтобы прогон не тащил правила,
# залитые другим демо (стор общий, и `-rule clear` тоже глобален).
#
# Причина не только в общем сторе. Правило нефазируемо по построению: оно уходит в
# КАЖДЫЙ ход любому агенту, включая первичный, - а весь смысл этой сборки в том, что
# мерило меняется вместе с фазой. Все инварианты здесь фазовые и записаны в
# `constraints` своих профилей. Прежняя версия демо держала три правила про блок-сводку
# и поплатилась: на терминальной стадии реплика «Задача завершена.» блока честно не
# несёт, и требование блока превращалось в нарушение, которого нет.
"$CLI" -rule clear || true

cat <<EOF

[setup] готово. Целевой репозиторий: $CTT_REPO (ветка $(git -C "$CTT_REPO" branch --show-current))

Сценарии - от гарантированного к исследовательскому:
  bash demo/project-fs/run-usage-report.sh     карта сетевого слоя -> docs/usage-network.md
  bash demo/project-fs/run-adr.sh              решение о хранении -> docs/adr-0001-local-persistence.md

Модель: gemini-2.5-flash (дефолт клиента). Судья удваивает вызовы на ход, а забракованный
ход добавляет ещё два - переписывание и повторный суд.

Аварийный выход, если прогон встал на повторяющемся [invariant] violated:
  JUDGE=0 bash demo/project-fs/run-usage-report.sh
EOF
